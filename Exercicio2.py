print('Neste programa iremos pedir 2 números do usuário para calcular soma, subtração, multiplicação e divisão.')

num1 = float(input('Para começar, escolha um número: '))
num2 = float(input('Escolha mais um número: '))

soma = num1 + num2
subtracao = num1 - num2
multiplicacao = num1 * num2
divisao = num1 / num2

print(f'Esta é a soma dos números: {soma}')
print(f'Esta é a subtração dos números: {subtracao}')
print(f'Esta é a multiplicação dos números: {multiplicacao}')
print(f'Esta é a divisão dos números: {divisao}')